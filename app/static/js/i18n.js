const DICTS = { zh: ZH, en: EN };

export const locale = DICTS[document.documentElement.dataset.locale] ? document.documentElement.dataset.locale : "zh";

/** 站名：自定义过 SITE_NAME 就照用，否则英文界面显示 Lumen。 */
export const brand = (siteName) => {
  const name = siteName || "星皓书房";
  return name === "星皓书房" && locale === "en" ? "Lumen" : name;
};

function pick(entry, vars) {
  if (entry == null) return null;
  if (typeof entry === "string") return entry;
  return vars && vars.n === 1 ? entry.one : entry.other;
}

/** 取词。变量用 {name} 占位；n 为 1 时英文走单数。 */
export function t(key, vars) {
  const text = pick(DICTS[locale][key] ?? DICTS.zh[key], vars);
  if (text == null) return key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] ?? m)) : text;
}

/** 某个键在当前语言里是否有译文。 */
export function has(key) {
  return key in DICTS[locale];
}

/** 后端错误码转文案；不是错误码就原样返回。 */
export function errText(code, vars) {
  const entry = DICTS[locale]["err." + code];
  return entry ? t("err." + code, vars) : code;
}

/** 翻译 HTML 里的静态标记。 */
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}
